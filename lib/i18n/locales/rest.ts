const names = (self: Record<keyof Messages['languageNames'], string>): Messages['languageNames'] => self

function pack(
  language: Messages['language'],
  languageNames: Messages['languageNames'],
  common: Messages['common'],
  role: Messages['role'],
  weekday: Messages['weekday'],
  extra: Pick<Messages, 'status' | 'theme' | 'nav' | 'landing' | 'auth' | 'settings' | 'account' | 'student' | 'teacher' | 'admin' | 'schedule' | 'charts' | 'chat'>
): Messages {
  return defineMessages({
    version: APP_VERSION,
    language,
    languageNames,
    common,
    role,
    weekday,
    ...extra,
  })
}

